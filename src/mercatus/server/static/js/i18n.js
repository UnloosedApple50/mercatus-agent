// Current language
let currentLang = localStorage.getItem("mercatus_lang") || "en";

// RTL languages
const RTL_LANGUAGES = new Set(["ar"]);

/**
 * Translate a key to the current language.
 * @param {string} key - The translation key.
 * @param {string} [fallback] - Fallback text if key not found.
 * @returns {string} Translated text.
 */
function t(key, fallback) {
    const entry = I18N_STRINGS[key];
    if (!entry) {
        return fallback || key;
    }
    return entry[currentLang] || entry["en"] || fallback || key;
}

/**
 * Set the current language.
 * @param {string} lang - Language code.
 */
function setLanguage(lang) {
    if (!(lang in I18N_LANGUAGES)) {
        console.warn(`Unknown language: ${lang}`);
        return;
    }
    currentLang = lang;
    localStorage.setItem("mercatus_lang", lang);

    // Apply RTL for Arabic
    if (RTL_LANGUAGES.has(lang)) {
        document.documentElement.setAttribute("dir", "rtl");
    } else {
        document.documentElement.setAttribute("dir", "ltr");
    }

    // Apply translations
    applyTranslations();

    // Dispatch event for other scripts
    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

/**
 * Get the current language.
 * @returns {string} Current language code.
 */
function getLanguage() {
    return currentLang;
}

/**
 * Get all available languages.
 * @returns {Object} Map of language codes to names.
 */
function getAvailableLanguages() {
    return I18N_LANGUAGES;
}

/**
 * Check if current language is RTL.
 * @returns {boolean}
 */
function isRTL() {
    return RTL_LANGUAGES.has(currentLang);
}

/**
 * Apply translations to all elements with data-i18n attribute.
 */
function applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        el.textContent = t(key);
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        const key = el.getAttribute("data-i18n-placeholder");
        el.setAttribute("placeholder", t(key));
    });

    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
        const key = el.getAttribute("data-i18n-title");
        el.setAttribute("title", t(key));
    });

    document.querySelectorAll("[data-i18n-label]").forEach((el) => {
        const key = el.getAttribute("data-i18n-label");
        el.setAttribute("aria-label", t(key));
    });
}

// Apply initial language settings
document.addEventListener("DOMContentLoaded", () => {
    setLanguage(currentLang);
});
